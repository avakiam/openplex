package docker

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/docker/docker/api/types/container"
	"github.com/docker/docker/api/types/mount"
	"github.com/docker/go-connections/nat"
)

// PowerDNS authoritative server.
const (
	DNSImage     = "powerdns/pdns-auth-50:5.0.8"
	DNSContainer = "openplex-dns"
	DNSVolume    = "openplex-dns-data" // the image ships an initialised SQLite DB; a volume copies it
	DNSAPIPort   = 7082                // PowerDNS HTTP API, published on 127.0.0.1 only
	dnsUID       = 953                 // pdns user inside the image
	labelConfig  = "dev.openplex.config"
)

// DNSAPIURL is where openplexd reaches the PowerDNS API.
func DNSAPIURL() string { return "http://127.0.0.1:" + strconv.Itoa(DNSAPIPort) }

// EnsureDNS runs PowerDNS answering on port 53 of the given host addresses
// (publishing on specific addresses avoids systemd-resolved's 127.0.0.53:53).
// The container is recreated when the image, addresses or API key change.
func (o *Orchestrator) EnsureDNS(ctx context.Context, apiKey string, listen []netip.Addr) error {
	if len(listen) == 0 {
		return fmt.Errorf("no address to answer DNS on")
	}
	conf := strings.Join([]string{
		"# Generated by openplexd — do not edit.",
		"api=yes", "api-key=" + apiKey,
		"webserver=yes", "webserver-address=0.0.0.0", "webserver-port=8081", "webserver-allow-from=0.0.0.0/0,::/0",
		"version-string=anonymous", "loglevel=4", "",
	}, "\n")
	dir := filepath.Join(o.cfg.DataDir, "dns")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	confPath := filepath.Join(dir, "openplex.conf")
	if err := writeFileAtomic(confPath, []byte(conf), 0o640); err != nil {
		return err
	}
	if err := os.Chown(confPath, 0, dnsUID); err != nil && !os.IsPermission(err) {
		return fmt.Errorf("chown dns config: %w", err)
	}
	_ = os.Chown(dir, 0, dnsUID)

	ports := nat.PortMap{}
	var addrs []string
	for _, a := range listen {
		h := a.String()
		addrs = append(addrs, h)
		for _, p := range []nat.Port{"53/udp", "53/tcp"} {
			ports[p] = append(ports[p], nat.PortBinding{HostIP: h, HostPort: "53"})
		}
	}
	ports["8081/tcp"] = []nat.PortBinding{{HostIP: "127.0.0.1", HostPort: strconv.Itoa(DNSAPIPort)}}
	sum := sha256.Sum256([]byte(DNSImage + "|" + strings.Join(addrs, ",") + "|" + conf + "|net=" + PublicNetwork))
	hash := hex.EncodeToString(sum[:8])

	c, err := o.findContainer(ctx, DNSContainer)
	if err != nil {
		return err
	}
	if c != nil && c.Config.Labels[labelConfig] == hash {
		if !c.State.Running {
			return o.cli.ContainerStart(ctx, c.ID, container.StartOptions{})
		}
		return nil
	}
	if c != nil {
		if err := o.cli.ContainerRemove(ctx, c.ID, container.RemoveOptions{Force: true}); err != nil {
			return fmt.Errorf("remove old dns: %w", err)
		}
	}
	if err := o.ensureImage(ctx, DNSImage); err != nil {
		return err
	}
	if err := o.ensurePublicNetwork(ctx); err != nil {
		return err
	}
	labels := managedLabels("dns")
	labels[labelConfig] = hash
	cc := &container.Config{
		Image:        DNSImage,
		Labels:       labels,
		ExposedPorts: nat.PortSet{"53/udp": {}, "53/tcp": {}, "8081/tcp": {}},
	}
	hc := &container.HostConfig{
		PortBindings:  ports,
		NetworkMode:   container.NetworkMode(PublicNetwork),
		RestartPolicy: container.RestartPolicy{Name: container.RestartPolicyUnlessStopped},
		Mounts: []mount.Mount{
			{Type: mount.TypeVolume, Source: DNSVolume, Target: "/var/lib/powerdns"},
			{Type: mount.TypeBind, Source: confPath, Target: "/etc/powerdns/pdns.d/openplex.conf", ReadOnly: true},
		},
		CapDrop:     []string{"ALL"},
		CapAdd:      []string{"NET_BIND_SERVICE"},
		SecurityOpt: []string{"no-new-privileges:true"},
		Resources:   container.Resources{Memory: 256 << 20},
		LogConfig:   container.LogConfig{Type: "json-file", Config: map[string]string{"max-size": "10m", "max-file": "3"}},
	}
	created, err := o.cli.ContainerCreate(ctx, cc, hc, publicEndpoint(), nil, DNSContainer)
	if err != nil {
		return fmt.Errorf("create dns: %w", err)
	}
	if err := o.cli.ContainerStart(ctx, created.ID, container.StartOptions{}); err != nil {
		_ = o.cli.ContainerRemove(ctx, created.ID, container.RemoveOptions{Force: true})
		return fmt.Errorf("start dns: %w", err)
	}
	o.log.Info("dns server started", "image", DNSImage, "addresses", addrs)
	return nil
}

// StopDNS removes the PowerDNS container (its data volume is kept).
func (o *Orchestrator) StopDNS(ctx context.Context) error {
	c, err := o.findContainer(ctx, DNSContainer)
	if err != nil || c == nil {
		return err
	}
	return o.cli.ContainerRemove(ctx, c.ID, container.RemoveOptions{Force: true})
}

// DNSRunning reports whether the PowerDNS container is up.
func (o *Orchestrator) DNSRunning(ctx context.Context) bool {
	c, err := o.findContainer(ctx, DNSContainer)
	return err == nil && c != nil && c.State.Running
}
