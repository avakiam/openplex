//go:embed all:webmail
var webmailFS embed.FS

// MasterUser is the Dovecot master login the webmail uses for one-click
// logins. It is only accepted from the mail network.
const MasterUser = "opx-webmail"

// TicketTTL is how long a one-click webmail link works (it is also single use).
const TicketTTL = 2 * time.Minute

// roundcubeGID is www-data in the Roundcube image: it must read the config.
const roundcubeGID = 33

// webmailKeys are generated once and kept in <data>/webmail/keys.json.
type webmailKeys struct {
	DESKey         string `json:"des_key"`         // Roundcube session encryption (24 chars)
	SSOKey         string `json:"sso_key"`         // hex HMAC key shared with the plugin
	MasterPassword string `json:"master_password"` // Dovecot master user's password
	MasterHash     string `json:"master_hash"`     // its SHA512-CRYPT (kept so the file stays stable)
}

func randHex(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err) // crypto/rand never fails on supported platforms
	}
	return hex.EncodeToString(b)
}

// loadKeys reads the webmail keys, creating them on first use.
func loadKeys(file string) (*webmailKeys, error) {
	var k webmailKeys
	if b, err := os.ReadFile(file); err == nil {
		if err := json.Unmarshal(b, &k); err != nil {
			return nil, fmt.Errorf("read %s: %w", file, err)
		}
		if k.DESKey != "" && k.SSOKey != "" && k.MasterPassword != "" && k.MasterHash != "" {
			return &k, nil
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	pw := randHex(24)
	k = webmailKeys{DESKey: randHex(12), SSOKey: randHex(32), MasterPassword: pw, MasterHash: HashPassword(pw)}
	b, _ := json.Marshal(k)
	if err := os.MkdirAll(filepath.Dir(file), 0o700); err != nil {
		return nil, err
	}
	if err := os.WriteFile(file, b, 0o600); err != nil {
		return nil, err
	}
	return &k, nil
}

// Ticket signs a single-use one-click login for address, checked by the
// Roundcube plugin: base64url(JSON).base64url(HMAC-SHA256).
func Ticket(ssoKeyHex, address string, now time.Time) (string, error) {
	key, err := hex.DecodeString(ssoKeyHex)
	if err != nil || len(key) < 16 {
		return "", errors.New("invalid webmail key")
	}
	payload, _ := json.Marshal(map[string]any{"u": address, "e": now.Add(TicketTTL).Unix(), "n": randHex(16)})
	p := base64.RawURLEncoding.EncodeToString(payload)
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(p))
	return p + "." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil)), nil
}

// WebmailCaptcha is the captcha the webmail login asks for.
type WebmailCaptcha struct {
	Provider, SiteKey, Secret string
}

// phpStr quotes s as a PHP single-quoted string.
func phpStr(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// webmailConfig renders the PHP file Roundcube includes after its own
// configuration. Values are re-validated: they end up in PHP source.
func webmailConfig(k *webmailKeys, mailNet, edgeNet string, c *WebmailCaptcha) ([]byte, error) {
	if !safeNet.MatchString(mailNet) || !safeNet.MatchString(edgeNet) {
		return nil, fmt.Errorf("invalid network ranges %q, %q", mailNet, edgeNet)
	}
	var b bytes.Buffer
	b.WriteString("<?php\n// Generated by openplexd — do not edit; changes are overwritten.\n")
	fmt.Fprintf(&b, "$config['des_key'] = %s;\n", phpStr(k.DESKey))
	b.WriteString("$config['product_name'] = 'Webmail';\n")
	// The mail server's certificate is for its public name; inside the
	// private mail network the container is reached by its own name.
	b.WriteString("$config['imap_conn_options'] = $config['smtp_conn_options'] = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false]];\n")
	b.WriteString("$config['smtp_user'] = '%u';\n$config['smtp_pass'] = '%p';\n")
	fmt.Fprintf(&b, "$config['proxy_whitelist'] = [%s];\n", phpStr(edgeNet)) // the edge: trust its X-Forwarded-*
	b.WriteString("$config['use_https'] = false;\n$config['ip_check'] = true;\n$config['session_lifetime'] = 60;\n")
	b.WriteString("$config['login_rate_limit'] = 5;\n$config['enable_installer'] = false;\n$config['support_url'] = '';\n")
	fmt.Fprintf(&b, "$config['openplex_sso_key'] = %s;\n", phpStr(k.SSOKey))
	fmt.Fprintf(&b, "$config['openplex_master'] = %s;\n", phpStr(MasterUser))
	fmt.Fprintf(&b, "$config['openplex_master_password'] = %s;\n", phpStr(k.MasterPassword))
	if c != nil {
		if _, ok := captcha.Providers[c.Provider]; !ok || !captcha.ValidKey(c.SiteKey) || !captcha.ValidKey(c.Secret) {
			return nil, errors.New("invalid captcha settings")
		}
		fmt.Fprintf(&b, "$config['openplex_captcha'] = ['provider' => %s, 'site_key' => %s, 'secret' => %s];\n",
			phpStr(c.Provider), phpStr(c.SiteKey), phpStr(c.Secret))
	}
	return b.Bytes(), nil
}

// pluginFiles returns the embedded Roundcube plugin (relative to the
// webmail dir) and a version that changes with its content.
func pluginFiles() (map[string][]byte, string) {
	files := map[string][]byte{}
	_ = fs.WalkDir(webmailFS, "webmail", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := webmailFS.ReadFile(p)
		if err != nil {
			return err
		}
		files[path.Join("plugin", strings.TrimPrefix(p, "webmail/"))] = b
		return nil
	})
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	h := sha256.New()
	for _, n := range names {
		h.Write([]byte(n))
		h.Write(files[n])
	}
	return files, hex.EncodeToString(h.Sum(nil))[:16]
}

// writeWebmail writes the plugin and configuration under dir. The config
// holds secrets: 0640, group www-data (the Roundcube user) only.
func writeWebmail(dir string, conf []byte) (version string, err error) {
	files, version := pluginFiles()
	for rel, data := range files {
		mode := os.FileMode(0o644)
		if strings.HasSuffix(rel, ".sh") {
			mode = 0o755 // run by the image's entrypoint
		}
		if err := writeIfChanged(filepath.Join(dir, filepath.FromSlash(rel)), data, mode, -1); err != nil {
			return "", err
		}
	}
	if err := writeIfChanged(filepath.Join(dir, "config", "openplex.inc.php"), conf, 0o640, roundcubeGID); err != nil {
		return "", err
	}
	return version, nil
}

func writeIfChanged(p string, data []byte, mode os.FileMode, gid int) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, data) {
		if st, err := os.Stat(p); err == nil && st.Mode().Perm() == mode {
			return nil
		}
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, data, mode); err != nil {
		return err
	}
	if err := os.Chmod(tmp, mode); err != nil { // not narrowed by the umask
		return err
	}
	if gid >= 0 && os.Geteuid() == 0 {
		if err := os.Chown(tmp, 0, gid); err != nil {
			return err
		}
	}
	return os.Rename(tmp, p)
}
