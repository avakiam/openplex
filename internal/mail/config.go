package mail

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Paths inside the container (docker-mailserver reads /tmp/docker-mailserver).
const (
	ContainerConfigDir = "/tmp/docker-mailserver"
	ContainerCert      = ContainerConfigDir + "/ssl/cert.pem"
	ContainerKey       = ContainerConfigDir + "/ssl/key.pem"
)

// DomainConfig is one domain as docker-mailserver needs it.
type DomainConfig struct {
	Name     string
	Selector string
	KeyPEM   string // DKIM private key
}

// MailboxConfig is one account.
type MailboxConfig struct {
	Address string
	Hash    string // {SHA512-CRYPT}$6$…
	QuotaMB int
}

// AliasConfig forwards Address.
type AliasConfig struct {
	Address      string
	Destinations []string
}

// Snapshot is everything the container configuration is rendered from.
type Snapshot struct {
	Domains   []DomainConfig
	Mailboxes []MailboxConfig
	Aliases   []AliasConfig
	Master    *MasterConfig // the webmail's master login, when the webmail runs
}

// MasterConfig is a Dovecot master user: it logs in as any mailbox
// ("<mailbox>*<name>") but only from Nets.
type MasterConfig struct {
	Name string
	Hash string
	Nets string // CIDR
}

var (
	safeAddr = regexp.MustCompile(`^[a-z0-9._%+-]+@[a-z0-9.-]+$`)
	safeHash = regexp.MustCompile(`^\{SHA512-CRYPT\}\$6\$[A-Za-z0-9./=$]+$`)
	safeHost = regexp.MustCompile(`^[a-z0-9.-]+$`)
	safeNet  = regexp.MustCompile(`^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$`)
)

// Files renders the configuration files, relative to the config dir. Every
// value is re-checked so a bad row can never inject configuration.
func Files(s Snapshot) (map[string][]byte, error) {
	var accounts, quotas, virtual, dkim bytes.Buffer
	out := map[string][]byte{}
	mbs := append([]MailboxConfig(nil), s.Mailboxes...)
	sort.Slice(mbs, func(i, j int) bool { return mbs[i].Address < mbs[j].Address })
	for _, m := range mbs {
		if !safeAddr.MatchString(m.Address) || !safeHash.MatchString(m.Hash) || m.QuotaMB < 1 {
			return nil, fmt.Errorf("mailbox %q: invalid row", m.Address)
		}
		fmt.Fprintf(&accounts, "%s|%s\n", m.Address, m.Hash)
		fmt.Fprintf(&quotas, "%s:%dM\n", m.Address, m.QuotaMB)
	}
	als := append([]AliasConfig(nil), s.Aliases...)
	sort.Slice(als, func(i, j int) bool { return als[i].Address < als[j].Address })
	for _, a := range als {
		if !safeAddr.MatchString(a.Address) || len(a.Destinations) == 0 {
			return nil, fmt.Errorf("alias %q: invalid row", a.Address)
		}
		for _, d := range a.Destinations {
			if !safeAddr.MatchString(d) {
				return nil, fmt.Errorf("alias %q: invalid destination %q", a.Address, d)
			}
		}
		fmt.Fprintf(&virtual, "%s %s\n", a.Address, strings.Join(a.Destinations, ","))
	}
	dkim.WriteString("# Generated by openplexd — do not edit.\nenabled = true;\nsign_authenticated = true;\nsign_local = true;\ntry_fallback = false;\n" +
		"use_domain = \"header\";\nuse_redis = false;\nuse_esld = true;\nallow_username_mismatch = true;\n" +
		// Only sign when the From: header and the envelope sender (which
		// SPOOF_PROTECTION ties to the login) share a domain: a tenant can't
		// get another tenant's domain signature on a forged From: header.
		"allow_hdrfrom_mismatch = false;\nallow_hdrfrom_mismatch_local = false;\nallow_hdrfrom_mismatch_sign_networks = false;\nallow_hdrfrom_multiple = false;\ncheck_pubkey = false;\n\ndomain {\n")
	doms := append([]DomainConfig(nil), s.Domains...)
	sort.Slice(doms, func(i, j int) bool { return doms[i].Name < doms[j].Name })
	for _, d := range doms {
		if !safeHost.MatchString(d.Name) || !safeHost.MatchString(d.Selector) || !strings.HasPrefix(d.KeyPEM, "-----BEGIN RSA PRIVATE KEY-----") {
			return nil, fmt.Errorf("domain %q: invalid row", d.Name)
		}
		key := "rspamd/dkim/" + d.Name + "." + d.Selector + ".key"
		out[key] = []byte(d.KeyPEM)
		fmt.Fprintf(&dkim, "    %s {\n        path = \"%s/%s\";\n        selector = \"%s\";\n    }\n", d.Name, ContainerConfigDir, key, d.Selector)
	}
	dkim.WriteString("}\n")
	var masters bytes.Buffer
	if m := s.Master; m != nil {
		if !safeHost.MatchString(m.Name) || !safeHash.MatchString(m.Hash) || !safeNet.MatchString(m.Nets) {
			return nil, fmt.Errorf("master user %q: invalid row", m.Name)
		}
		// docker-mailserver turns "name|rest" into the passwd-file line
		// "name:rest"; the sixth field after the password holds extra fields.
		fmt.Fprintf(&masters, "%s|%s::::::allow_nets=%s\n", m.Name, m.Hash, m.Nets)
	}
	out["dovecot-masters.cf"] = masters.Bytes()
	out["postfix-accounts.cf"] = accounts.Bytes()
	out["dovecot-quotas.cf"] = quotas.Bytes()
	out["postfix-virtual.cf"] = virtual.Bytes()
	out["rspamd/override.d/dkim_signing.conf"] = dkim.Bytes()
	return out, nil
}

// WriteFiles writes files under dir, only touching those whose content
// changed (each write makes the container reload), and removes DKIM keys
// of domains that are gone. It reports whether anything changed.
func WriteFiles(dir string, files map[string][]byte) (bool, error) {
	changed := false
	for rel, data := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, data) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return changed, err
		}
		// Readable inside the container by Rspamd and Dovecot; the data dir
		// itself is 0700 on the host.
		tmp := p + ".tmp"
		if err := os.WriteFile(tmp, data, 0o644); err != nil {
			return changed, err
		}
		if err := os.Rename(tmp, p); err != nil {
			return changed, err
		}
		changed = true
	}
	keys, _ := filepath.Glob(filepath.Join(dir, "rspamd", "dkim", "*.key"))
	for _, k := range keys {
		rel, _ := filepath.Rel(dir, k)
		if _, ok := files[filepath.ToSlash(rel)]; !ok {
			_ = os.Remove(k)
			changed = true
		}
	}
	return changed, nil
}
